---------------------------------------------------------
-- 1. Total Revenue
--
-- Business Question:
-- What is the total revenue generated by completed orders?
--
-- SQL Concept:
-- SUM() + JOIN + filtering
---------------------------------------------------------
SELECT
    ROUND(
        SUM(oi.quantity * oi.unit_price),
        2
    ) AS total_revenue
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
WHERE o.status = 'completed';


---------------------------------------------------------
-- 2. Total Completed Orders
--
-- Business Question:
-- How many orders were successfully completed?
--
-- SQL Concept:
-- COUNT() + filtering
---------------------------------------------------------
SELECT
    COUNT(*) AS total_completed_orders
FROM orders
WHERE status = 'completed';


---------------------------------------------------------
-- 3. Average Order Value
--
-- Business Question:
-- What is the average value of a completed order?
--
-- SQL Concept:
-- CTE + SUM() + AVG()
---------------------------------------------------------
WITH order_totals AS (
    SELECT
        o.order_id,
        SUM(oi.quantity * oi.unit_price) AS order_total
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    WHERE o.status = 'completed'
    GROUP BY o.order_id
)
SELECT
    ROUND(
        AVG(order_total),
        2
    ) AS average_order_value
FROM order_totals;


---------------------------------------------------------
-- 4. Active Customers
--
-- Business Question:
-- How many unique customers have completed at least
-- one purchase?
--
-- SQL Concept:
-- COUNT(DISTINCT ...)
---------------------------------------------------------
SELECT
    COUNT(DISTINCT customer_id) AS active_customers
FROM orders
WHERE status = 'completed';


---------------------------------------------------------
-- 5. Average Revenue per Active Customer
--
-- Business Question:
-- How much revenue does an active customer generate
-- on average?
--
-- SQL Concept:
-- CTE + aggregation + AVG()
---------------------------------------------------------
WITH customer_revenue AS (
    SELECT
        o.customer_id,
        SUM(oi.quantity * oi.unit_price) AS total_revenue
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    WHERE o.status = 'completed'
    GROUP BY o.customer_id
)
SELECT
    ROUND(
        AVG(total_revenue),
        2
    ) AS average_revenue_per_customer
FROM customer_revenue;


---------------------------------------------------------
-- 6. Repeat Customer Rate
--
-- Business Question:
-- What percentage of active customers have completed
-- more than one order?
--
-- SQL Concept:
-- CTE + conditional aggregation
---------------------------------------------------------
WITH customer_orders AS (
    SELECT
        customer_id,
        COUNT(order_id) AS completed_orders
    FROM orders
    WHERE status = 'completed'
    GROUP BY customer_id
)
SELECT
    ROUND(
        100.0
        * COUNT(*) FILTER (WHERE completed_orders > 1)
        / NULLIF(COUNT(*), 0),
        2
    ) AS repeat_customer_rate_pct
FROM customer_orders;


---------------------------------------------------------
-- 7. Cancellation Rate
--
-- Business Question:
-- What percentage of all orders were cancelled?
--
-- SQL Concept:
-- Conditional aggregation
---------------------------------------------------------
SELECT
    ROUND(
        100.0
        * COUNT(*) FILTER (WHERE status = 'cancelled')
        / NULLIF(COUNT(*), 0),
        2
    ) AS cancellation_rate_pct
FROM orders;


---------------------------------------------------------
-- 8. Gross Margin by Product
--
-- Business Question:
-- Which products generate the highest gross margin
-- from completed orders?
--
-- SQL Concept:
-- Revenue - Cost
---------------------------------------------------------
SELECT
    p.product_id,
    p.product_name,
    ROUND(
        SUM(
            oi.quantity
            * (oi.unit_price - p.cost_price)
        ),
        2
    ) AS gross_margin
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.status = 'completed'
GROUP BY
    p.product_id,
    p.product_name
ORDER BY gross_margin DESC;


---------------------------------------------------------
-- 9. Gross Margin Rate
--
-- Business Question:
-- What percentage of revenue remains after product cost?
--
-- SQL Concept:
-- Gross margin / Revenue
---------------------------------------------------------
SELECT
    ROUND(
        100.0
        * SUM(
            oi.quantity
            * (oi.unit_price - p.cost_price)
        )
        / NULLIF(
            SUM(oi.quantity * oi.unit_price),
            0
        ),
        2
    ) AS gross_margin_rate_pct
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id
JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.status = 'completed';


---------------------------------------------------------
-- 10. Revenue Contribution by Category
--
-- Business Question:
-- What percentage of total revenue is generated by
-- each product category?
--
-- SQL Concept:
-- CTE + window function
---------------------------------------------------------
WITH category_revenue AS (
    SELECT
        cat.category_name,
        SUM(oi.quantity * oi.unit_price) AS revenue
    FROM categories cat
    JOIN products p
        ON cat.category_id = p.category_id
    JOIN order_items oi
        ON p.product_id = oi.product_id
    JOIN orders o
        ON oi.order_id = o.order_id
    WHERE o.status = 'completed'
    GROUP BY cat.category_name
)
SELECT
    category_name,
    revenue,
    ROUND(
        100.0
        * revenue
        / NULLIF(
            SUM(revenue) OVER (),
            0
        ),
        2
    ) AS revenue_contribution_pct
FROM category_revenue
ORDER BY revenue_contribution_pct DESC;